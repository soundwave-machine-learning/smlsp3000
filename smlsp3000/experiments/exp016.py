"""CHAIN-EXP-016 — Null-framework self-test (SIMULATION).

Question: does the alignment/null framework null an ideal reference to its own
numerical floor, and does it recover known perturbations from independently
generated truth?

Decision criterion (source, docs/EXPERIMENT_PLAN.md): “Framework accepted when
its own floor is known.” The identical-array case must be *exactly* zero; the
perturbation cases report recovery error and residual floor. No hardware
tolerance is derived here (G-06 is a Sprint 2 owner gate).
"""
from __future__ import annotations

import json
from dataclasses import dataclass, asdict
from pathlib import Path

import numpy as np

from .. import environment as env
from ..hashing import sha256_array, sha256_bytes, write_manifest
from ..nullframework import (ALGORITHM_VERSION, PREPROCESSING_VERSION, EvaluatorConfig, align,
                             null_identical, null_metrics, residual_spectrum)
from ..schemas import EXPERIMENT_RESULT_RECORD, validate
from ..stimuli import self_test_stimulus

EXPERIMENT_ID = "CHAIN-EXP-016"


@dataclass(frozen=True)
class Perturbation:
    name: str
    clock_ratio: float = 1.0
    delay_s: float = 0.0
    polarity: int = 1
    gain: float = 1.0
    dc: float = 0.0


def default_cases() -> list[Perturbation]:
    fs = 192000.0
    return [
        Perturbation("none"),
        Perturbation("ratio_plus_37ppm", clock_ratio=1.0 + 37e-6),
        Perturbation("ratio_minus_120ppm", clock_ratio=1.0 - 120e-6),
        Perturbation("delay_0p37_samples", delay_s=0.37 / fs),
        Perturbation("delay_3p30_samples", delay_s=3.30 / fs),
        Perturbation("delay_17p25_samples", delay_s=17.25 / fs),
        Perturbation("polarity_inverted", polarity=-1),
        Perturbation("gain_minus_1dB", gain=10 ** (-1.0 / 20.0)),
        Perturbation("gain_plus_1dB", gain=10 ** (1.0 / 20.0)),
        Perturbation("dc_plus_0p01", dc=0.01),
        Perturbation("combined", clock_ratio=1.0 + 61e-6, delay_s=7.63 / fs, polarity=-1, gain=10 ** (-2.5 / 20.0), dc=-0.004),
    ]


def default_config() -> dict:
    return {
        "experiment_id": EXPERIMENT_ID,
        "artifact_class": "SIMULATION",
        "stimulus": self_test_stimulus().to_dict(),
        "evaluator": EvaluatorConfig().to_dict(),
        "cases": [asdict(c) for c in default_cases()],
        "notes": "Independent truth: captures are generated by analytic evaluation of the stimulus at perturbed instants, never by the evaluator's resampler.",
    }


def run(out_dir: str | Path, config: dict | None = None, command: str = "") -> dict:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    cfg = config or default_config()
    cfg_bytes = json.dumps(cfg, indent=1, sort_keys=True).encode()
    (out / "config.json").write_bytes(cfg_bytes)
    cfg_hash = sha256_bytes(cfg_bytes)

    stim = self_test_stimulus(**{k: v for k, v in {
        "sample_rate_hz": cfg["stimulus"]["sample_rate_hz"]}.items()})
    ecfg = EvaluatorConfig(**{k: (tuple(v) if isinstance(v, list) else v) for k, v in cfg["evaluator"].items()})
    fs = float(stim.sample_rate_hz)
    ref = stim.render()
    raw_hashes = {"reference_float64": sha256_array(ref)}

    # Step A: identical arrays, no preprocessing → must be exactly zero.
    res0 = null_identical(ref, ref.copy())
    identical_exact_zero = bool(np.all(res0 == 0.0)) and bool(np.array_equal(ref, ref.copy()))

    # Step B/C: perturbation cases through the full pipeline.
    prog = stim.segment("program")
    a = int(round((prog.start_s + ecfg.analysis_trim_s) * fs))
    b = int(round((prog.end_s - ecfg.analysis_trim_s) * fs))
    cases_out = []
    for case in cfg["cases"]:
        p = Perturbation(**case)
        cap = stim.render_perturbed(p.clock_ratio, p.delay_s, p.polarity, p.gain, p.dc)
        raw_hashes[f"capture_{p.name}_float64"] = sha256_array(cap)
        est, corrected, ref_hp = align(ref, cap, stim, ecfg)
        m = null_metrics(ref_hp[a:b], corrected[a:b], fs, ecfg)
        f, db = residual_spectrum(ref_hp[a:b], corrected[a:b], fs)
        csv = out / f"residual_spectrum_{p.name}.csv"
        with open(csv, "w", encoding="utf-8") as fh:
            fh.write("# SIMULATION; CHAIN-EXP-016 residual spectrum; frequency_hz,residual_db_re_fs_sine\n")
            for fi, di in zip(f, db):
                fh.write(f"{fi:.3f},{di:.3f}\n")
        true_delay_samples = p.delay_s * fs
        cases_out.append({
            "case": p.name,
            "true": {"clock_ratio": p.clock_ratio, "delay_samples": true_delay_samples, "polarity": p.polarity, "gain": p.gain, "dc": p.dc},
            "estimated": est.to_dict(),
            "recovery_error": {
                "clock_ratio_ppm": float((est.clock_ratio - p.clock_ratio) * 1e6),
                "delay_samples": float(est.delay_samples - true_delay_samples),
                "polarity_correct": bool(est.polarity == p.polarity),
                "gain_db": float(20.0 * np.log10(est.gain / p.gain)),
                "dc_capture_error": float(est.dc_capture - p.dc),
                "delay_end_vs_start_samples": float(est.delay_end_check_samples - est.delay_samples),
            },
            "null_metrics": m.to_dict(),
            "residual_spectrum_csv": csv.name,
        })

    floor = {
        "max_residual_rms_db_re_signal_over_cases": max(c["null_metrics"]["residual_rms_db_re_signal"] for c in cases_out),
        "max_abs_clock_ratio_error_ppm": max(abs(c["recovery_error"]["clock_ratio_ppm"]) for c in cases_out),
        "max_abs_delay_error_samples": max(abs(c["recovery_error"]["delay_samples"]) for c in cases_out),
        "max_abs_gain_error_db": max(abs(c["recovery_error"]["gain_db"]) for c in cases_out),
        "all_polarity_correct": all(c["recovery_error"]["polarity_correct"] for c in cases_out),
        "none_case_residual_rms_db_re_signal": cases_out[0]["null_metrics"]["residual_rms_db_re_signal"],
    }
    outcome = "PASS" if identical_exact_zero and floor["all_polarity_correct"] else "FAIL"

    record = {
        "experiment_id": EXPERIMENT_ID,
        "question": "Null-framework self-test",
        "hypothesis": "Framework nulls an ideal reference to numerical floor",
        "requirement_ids": ["REQ-003"],
        "debt_ids": [],
        "artifact_class": "SIMULATION",
        "dataset_role": "SELF_NULL",
        "input_config_sha256": cfg_hash,
        "unit_routes": "N/A (simulation; no hardware unit)",
        "software": env.software_record(),
        "source_commit": env.git_describe(),
        "environment": env.environment_record(),
        "command": command or "python3 -m smlsp3000.runner run CHAIN-EXP-016",
        "algorithm_version": ALGORITHM_VERSION,
        "preprocessing_version": PREPROCESSING_VERSION,
        "raw_output_sha256": raw_hashes,
        "metric_definitions": {
            "residual_rms_db_re_signal": "20*log10(rms(ref-cand)/rms(ref)) over the trimmed program window",
            "residual_peak_dbfs": "20*log10(max|ref-cand|), 1.0 = synthetic full scale",
            "correlation": "Pearson correlation of ref and cand over the window",
            "per_band_residual_db": "10*log10(sum|E|^2 / sum|R|^2) per band, Hann-windowed rfft",
            "clock_ratio": "f_pilot(capture)/f_pilot(reference), mean of start/end pilots; drift = (end-start) ppm",
            "delay_samples": "integer lag from pilot envelope cross-correlation + sub-sample from pilot phase",
            "gain": "calibration-tone amplitude ratio (capture/reference)",
            "undefined_handling": "relative metrics are null when signal RMS is zero; absolute residual always recorded",
        },
        "threshold_policy": {
            "revision": "none",
            "status": "Identical-array residual must be exactly zero (structural). Nonzero acceptance tolerances are NOT defined here; G-06 (hardware self-null floor) sets them in Sprint 2. The values under 'results.floor' are the measured evaluator floor on this build.",
        },
        "uncertainty": {"note": "Deterministic simulation; floor values are same-build regression goldens (domain 2), not hardware tolerances."},
        "results": {"identical_array_exact_zero": identical_exact_zero, "floor": floor, "cases": cases_out},
        "outcome": outcome,
        "limitations": [
            "Synthetic analytic truth only; no hardware, no noise model, no time-varying drift (by policy one constant ratio).",
            "Floor includes Kaiser-sinc interpolation error and first-order DC high-pass; values are specific to this stimulus band (50 Hz–18 kHz) at 192 kHz.",
            "Cross-platform floating-point differences may change low-order digits of floor values; same-build reproduction is exact.",
        ],
        "resulting_decision": "G-02: framework floor is known and recorded; framework may be used for hardware comparison once G-06 thresholds exist.",
        "timestamp_utc": env.utc_now(),
    }
    problems = validate(record, EXPERIMENT_RESULT_RECORD)
    if problems:
        raise RuntimeError("result record does not conform to EXPERIMENT_RESULT_RECORD: " + "; ".join(problems))
    (out / "result.json").write_text(json.dumps(record, indent=1, sort_keys=True), encoding="utf-8")
    files = [p.name for p in out.iterdir() if p.is_file() and p.name != "manifest.sha256"]
    write_manifest(out, files)
    return record
